#!/usr/bin/env python3
"""Turn `data/dialects/**` into a C++ translation unit the library can link (CPP_PINYIN2_EMBED_DICTS).

Why this exists: a single-file deployment (one Windows .exe, an AppImage, a Unity/UE plugin, a mobile app
bundle) cannot carry a `share/cpp-pinyin2/dict` tree next to the binary, and a static build has no module
anchor to resolve one against. Embedding the tables removes the resource directory from the picture entirely
(D3 of docs/DECISIONS.md section 4.1).

WHAT THIS WRITES. One file with
  * one string literal per table (chunked, because MSVC refuses a string literal over ~16 KB: each chunk is
    emitted as its own adjacent literal and C++ concatenates them), every byte escaped as `\\xNN` -- escaping
    EVERY byte is what makes the result binary-safe, and it also keeps a literal from swallowing the following
    character as a hex digit;
  * one row per table (`<dialect>/<name>` + bytes + size);
  * `cpp_pinyin::v2::detail::findEmbeddedTable()`, matched by the last two path components of the request.

Determinism: dialects and files are sorted, so two runs over the same tree produce byte-identical output.

Usage:
    python tools/embed_dialects.py --out <build>/embedded_dialects.cpp --all
    python tools/embed_dialects.py --out <build>/embedded_dialects.cpp --dialects mandarin,cantonese
"""

from __future__ import annotations

import argparse
import pathlib
import sys

#: Bytes per string literal. A literal of N bytes becomes 4*N characters (`\xNN` each); 2000 keeps every chunk
#: under MSVC's ~16 KB per-literal ceiling while keeping the generated file readable.
CHUNK = 2000


def escape_literals(data: bytes, chunk: int = CHUNK) -> list[str]:
    """`data` as a list of quoted C++ string literals whose concatenation is `data`, byte for byte."""
    pieces: list[str] = []
    for start in range(0, len(data), chunk):
        piece = data[start : start + chunk]
        pieces.append('"' + "".join("\\x%02x" % byte for byte in piece) + '"')
    return pieces or ['""']


def collect(data_dir: pathlib.Path, dialects: list[str]) -> list[tuple[str, str, bytes]]:
    """`(dialect, file name, bytes)` for every regular file of every requested dialect, sorted."""
    rows: list[tuple[str, str, bytes]] = []
    for dialect in sorted(dialects):
        directory = data_dir / dialect
        if not directory.is_dir():
            raise SystemExit(f"no such dialect directory: {directory}")
        for path in sorted(directory.iterdir()):
            if path.is_file():
                rows.append((dialect, path.name, path.read_bytes()))
    return rows


def render(rows: list[tuple[str, str, bytes]]) -> str:
    lines: list[str] = [
        "// Generated by tools/embed_dialects.py -- DO NOT EDIT.",
        "//",
        "// Built with CPP_PINYIN2_EMBED_DICTS: the dictionary tables below are part of the library, which is what",
        "// lets a single-file deployment run with no resource directory at all. Licensing follows the tables:",
        "// each dialect carries its own License.txt in this file, byte for byte.",
        "",
        '#include "EmbeddedTables.h"',
        "",
        "namespace cpp_pinyin::v2::detail",
        "{",
        "    namespace",
        "    {",
    ]

    names: list[str] = []
    for dialect, name, data in rows:
        identifier = "k" + dialect.title() + "".join(part.title() for part in name.replace(".", "_").split("_"))
        names.append(identifier)
        lines.append(f"        // data/dialects/{dialect}/{name} -- {len(data)} byte(s)")
        literals = escape_literals(data)
        lines.append(f"        const char {identifier}[] =")
        for index, literal in enumerate(literals):
            suffix = ";" if index == len(literals) - 1 else ""
            lines.append(f"            {literal}{suffix}")
        lines.append("")

    lines += [
        "        struct Row {",
        "            const char *dialect;",
        "            const char *name;",
        "            const char *data;",
        "            std::size_t size;",
        "        };",
        "",
        "        const Row kRows[] = {",
    ]
    for (dialect, name, _), identifier in zip(rows, names):
        lines.append(
            f'            {{"{dialect}", "{name}", {identifier}, sizeof {identifier} - 1}},'
        )
    lines += [
        "        };",
        "    }  // namespace",
        "",
        "    EmbeddedTable findEmbeddedTable(const std::filesystem::path &requested) {",
        "        // Matched by the last two components, so the caller's dictionary root does not have to exist or",
        "        // match anything: a build that embeds its data answers for whatever root the host passed.",
        "        const std::filesystem::path name = requested.filename();",
        "        const std::filesystem::path dialect = requested.parent_path().filename();",
        "        for (const Row &row : kRows)",
        "            if (name == row.name && dialect == row.dialect)",
        "                return {row.data, row.size};",
        "        return {nullptr, 0};",
        "    }",
        "}  // namespace cpp_pinyin::v2::detail",
        "",
    ]
    return "\n".join(lines)


def self_test() -> int:
    """Prove the escaping is byte-exact, including NULs, backslashes, quotes and a chunk boundary."""
    failures = 0
    cases = [
        b"",
        b"a",
        b"\x00\x01\xff",
        b'quote " and backslash \\ and %%s',
        b"line\r\nline2\n",
        bytes(range(256)),
        b"x" * (CHUNK + 7),
    ]
    # Round-trip through the C++ rules: adjacent literals concatenate; inside one, `\xNN` is exactly one byte.
    for index, case in enumerate(cases):
        literals = escape_literals(case)
        decoded = bytearray()
        for literal in literals:
            if not literal.startswith('"') or not literal.endswith('"'):
                print(f"  FAIL case {index}: not a quoted literal")
                failures += 1
                break
            text = literal[1:-1]
            offset = 0
            while offset < len(text):
                if text[offset] == "\\" and offset + 3 < len(text) and text[offset + 1] == "x":
                    decoded.append(int(text[offset + 2 : offset + 4], 16))
                    offset += 4
                    continue
                print(f"  FAIL case {index}: unescaped byte {text[offset]!r} at {offset}")
                failures += 1
                break
        else:
            if bytes(decoded) != case:
                print(f"  FAIL case {index}: {len(decoded)} bytes decoded, expected {len(case)}")
                failures += 1
    print(f"SELF-TEST: {len(cases) - failures}/{len(cases)} case(s) round-trip byte-exactly")
    return 1 if failures else 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=pathlib.Path, help="file to write")
    parser.add_argument("--data", type=pathlib.Path, default=None, help="data/dialects directory")
    parser.add_argument("--dialects", default="", help="comma-separated dialect directory names")
    parser.add_argument("--all", action="store_true", help="every directory under --data")
    parser.add_argument("--self-test", action="store_true", help="check the escaping, write nothing")
    args = parser.parse_args(argv)

    if args.self_test:
        return self_test()

    if args.out is None:
        parser.error("--out is required")

    data_dir = args.data or (pathlib.Path(__file__).resolve().parents[1] / "data" / "dialects")
    dialects = [name for name in (part.strip() for part in args.dialects.split(",")) if name]
    if args.all:
        dialects = sorted(entry.name for entry in data_dir.iterdir() if entry.is_dir())
    if not dialects:
        parser.error("pass --all or --dialects")

    rows = collect(data_dir, dialects)
    if not rows:
        parser.error(f"nothing to embed: {data_dir} holds no files for {dialects}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(rows), encoding="utf-8", newline="\n")
    total = sum(len(data) for _, _, data in rows)
    print(f"embedded {len(rows)} table(s) from {len(dialects)} dialect(s), {total} byte(s) -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
