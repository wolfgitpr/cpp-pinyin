#!/usr/bin/env python3
"""Write the C# shell's generated build info from the two sources of truth.

WHAT THIS WRITES AND WHY IT IS GENERATED RATHER THAN WRITTEN BY HAND:

* ``csharp/CppPinyin/version.props`` -- ``<Version>`` for MSBuild, which is what ``dotnet pack``
  puts into the nuspec. The version has exactly one source of truth, ``CMakeLists.txt``
  (``project(cpp-pinyin2 VERSION x.y.z)``), exactly as the Python shell's ``_version.py`` does
  (PLUGIN doc section 6.8.5, version chain places 3 and 5).
* ``csharp/CppPinyin/BuildInfo.g.props`` -- ``NativeLibraryName`` and ``Commit``. The native file
  name differs by toolchain (MinGW produces ``libcpp-pinyin2``, MSVC ``cpp-pinyin2``), so decision
  D20=A says no shell may hardcode it: it is recorded here at build time from the library that was
  actually built. ``DllImport`` needs a compile-time constant, which is why this is a C# source
  file and not an MSBuild property.

Both files are gitignored, and the project fails to build without them, so a stale or missing copy
cannot pass as current.

    python csharp/tools/emit_build_info.py --native <path to built library> [--commit <sha>]
    python csharp/tools/emit_build_info.py --check --native <path>      # CI: verify, do not write

``--check`` is the self-test the tooling discipline asks for: it recomputes both files and reports a
mismatch instead of rewriting them, so a tree that was built from a different version fails loudly.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parents[2]
PROJECT = ROOT / "csharp" / "CppPinyin"
VERSION_PROPS = PROJECT / "version.props"
BUILD_INFO = PROJECT / "BuildInfo.g.cs"

#: Suffixes the OS loader adds itself: the recorded name is what DllImport should be given.
LIBRARY_SUFFIXES = (".dll", ".so", ".dylib")


def version_from_cmake(cmake_lists: Path) -> str:
    """Parse ``project(cpp-pinyin2 VERSION x.y.z)`` -- the single source of truth."""
    if not cmake_lists.is_file():
        raise SystemExit(f"FATAL: {cmake_lists} is missing; cannot find the version")
    text = cmake_lists.read_text(encoding="utf-8")
    match = re.search(r"project\s*\(\s*cpp-pinyin2\s+VERSION\s+(\d+\.\d+\.\d+)", text)
    if not match:
        raise SystemExit(f"FATAL: no 'project(cpp-pinyin2 VERSION x.y.z)' line in {cmake_lists}")
    return match.group(1)


def library_name_from(native: Path) -> str:
    """The library's file name without the suffix the loader appends."""
    if not native.is_file():
        raise SystemExit(f"FATAL: {native} does not exist; build the native library first")
    name = native.name
    for suffix in LIBRARY_SUFFIXES:
        if name.endswith(suffix):
            return name[: -len(suffix)]
    return name


def render_version_props(version: str) -> str:
    return (
        "<!-- Generated by csharp/tools/emit_build_info.py from CMakeLists.txt. Do not edit; do not commit. -->\n"
        "<Project>\n"
        "  <PropertyGroup>\n"
        f"    <Version>{version}</Version>\n"
        "  </PropertyGroup>\n"
        "</Project>\n"
    )


def render_build_info(library: str, commit: str) -> str:
    return (
        "// Generated by csharp/tools/emit_build_info.py. Do not edit; do not commit.\n"
        "//\n"
        "// NativeLibraryName is recorded from the library that was actually built (decision D20=A):\n"
        "// MinGW produces libcpp-pinyin2, MSVC cpp-pinyin2, and no shell may hardcode either. It has to be\n"
        "// a compile-time constant, because DllImport requires one -- which is why this is a C# source\n"
        "// file and not an MSBuild property. (An earlier draft put the name in <DefineConstants>;\n"
        "// that is a preprocessor symbol, not a string constant, and cannot be used by DllImport.)\n"
        "namespace CppPinyin2\n"
        "{\n"
        "    internal static class BuildInfo\n"
        "    {\n"
        f'        internal const string NativeLibraryName = "{library}";\n'
        f'        internal const string Commit = "{commit}";\n'
        "    }\n"
        "}\n"
    )


def main(argv: Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--native", required=True, help="the native library that was built")
    parser.add_argument("--commit", default="unknown", help="recorded commit (not required to be HEAD)")
    parser.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 on drift")
    options = parser.parse_args(argv)

    version = version_from_cmake(ROOT / "CMakeLists.txt")
    library = library_name_from(Path(options.native))
    commit = options.commit.strip() or "unknown"

    version_text = render_version_props(version)
    build_info_text = render_build_info(library, commit)

    print(f"version   = {version} (from CMakeLists.txt)")
    print(f"library   = {library} (from {options.native})")
    print(f"commit    = {commit}")

    if options.check:
        problems = []
        for path, expected in ((VERSION_PROPS, version_text), (BUILD_INFO, build_info_text)):
            if not path.is_file():
                problems.append(f"{path.relative_to(ROOT)} is missing (run without --check to write it)")
                continue
            actual = path.read_text(encoding="utf-8")
            if actual != expected:
                problems.append(
                    f"{path.relative_to(ROOT)} does not match what this tool would generate "
                    f"(sha256 {hashlib.sha256(actual.encode('utf-8')).hexdigest()[:16]} vs "
                    f"{hashlib.sha256(expected.encode('utf-8')).hexdigest()[:16]})"
                )
        for problem in problems:
            print(f"FAIL  {problem}")
        if problems:
            print(f"\n{len(problems)} problem(s)")
            return 1
        print("PASS  both generated files match their sources of truth")
        return 0

    PROJECT.mkdir(parents=True, exist_ok=True)
    # LF on purpose: the files must be byte-stable across platforms, and a text-mode write on Windows
    # would turn every "\n" into "\r\n".
    # open(..., newline="\n") rather than Path.write_text(newline=...): the keyword only exists from
    # Python 3.10 and this repository's declared Python floor is 3.9. The board found the same pattern in
    # python/tools/build_native.py, where it was a hard TypeError.
    for path, text in ((VERSION_PROPS, version_text), (BUILD_INFO, build_info_text)):
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    print(f"wrote {VERSION_PROPS.relative_to(ROOT)} and {BUILD_INFO.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
