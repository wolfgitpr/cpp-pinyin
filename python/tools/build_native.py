#!/usr/bin/env python3
"""Assemble the Python package's native payload: ``_version.py``, the library, the dictionaries.

The order is enforced rather than documented. The version is written FIRST, read from the single
source (the root ``CMakeLists.txt`` ``project(... VERSION)``); then the shared library is built;
then both are staged into ``python/cpp_pinyin2/``. A build that cannot determine the version fails
loudly instead of falling back to ``0.0.0`` -- a package that reports a version nobody built is
worse than a package that refuses to build (`docs/DECISIONS.md` §2.1).

Usage:
    python python/tools/build_native.py [--build-dir DIR] [--config Release]
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import List, Sequence

ROOT = Path(__file__).resolve().parents[2]
PKG = ROOT / "python" / "cpp_pinyin2"
NATIVE_DIR = PKG / "_native"
DICT_DIR = PKG / "data" / "dict"

#: Hardcoded whitelist, deliberately not `data/dialects/*`: this project ships exactly two dialects
#: and a stray directory must not end up inside a wheel (section 6.8.1, rule 2 / section 6.8.6).
DIALECTS = ("mandarin", "cantonese")

#: Required tables per dialect, so a half-copied dictionary cannot pass as a complete one.
REQUIRED_TABLES = ("word.txt", "phrases_dict.txt", "phrases_map.txt", "trans_word.txt")

VERSION_RE = re.compile(r"project\(\s*cpp-pinyin2\s+VERSION\s+([0-9]+\.[0-9]+\.[0-9]+)")
SUFFIXES = (".dll", ".so", ".dylib")


def run(args: Sequence[str]) -> None:
    """Run a command, echoing it and failing loudly (no silent exit-0 path)."""
    print("+ " + " ".join(args), flush=True)
    subprocess.run(list(args), check=True)


def single_source_version() -> str:
    text = (ROOT / "CMakeLists.txt").read_text(encoding="utf-8")
    match = VERSION_RE.search(text)
    if not match:
        raise SystemExit(
            "FATAL: no `project(cpp-pinyin2 VERSION x.y.z)` found in CMakeLists.txt. "
            "That line is the only authority for the version; this script will not guess one."
        )
    return match.group(1)


def commit_id() -> str:
    """The commit this build was made from, or "unknown" when git cannot answer."""
    try:
        done = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return done.stdout.strip() or "unknown"


def write_version(version: str, commit: str) -> Path:
    target = PKG / "_version.py"
    text = (
        '"""Generated by python/tools/build_native.py -- do not edit, do not commit."""\n'
        "\n"
        f'__version__ = "{version}"\n'
        f'__commit__ = "{commit}"\n'
    )
    # open(..., newline="\n") rather than Path.write_text(newline=...): the latter only exists from
    # Python 3.10, while this package declares python_requires >= 3.9 (user decision 2026-10-10; it was
    # >= 3.8 before that). The floor is a claim the tree has already seen proven wrong once -- the board
    # caught build_native.py raising TypeError on Python 3.8 while packaging -- which is exactly why the
    # floor is now the oldest interpreter the CI matrix actually runs.
    with target.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {target.relative_to(ROOT)}: version={version} commit={commit}")
    return target


def cmake_generator() -> List[str]:
    # Ninja when available: the project's own trees and its CI use it, and on Windows without
    # MSVC CMake's default generator would not be usable at all.
    return ["-G", "Ninja"] if shutil.which("ninja") else []


def configure_and_build(build_dir: Path, config: str) -> None:
    args = [
        "cmake",
        "-S",
        str(ROOT),
        "-B",
        str(build_dir),
        *cmake_generator(),
    ]
    # A FRESH directory gets the wheel's shape. An EXISTING one keeps its own: reconfiguring the preset's tree with
    # tests and install OFF made the next `ctest` fail four install tests, and it happened twice on 2026-10-21 even
    # though docs/RELEASE_CHECKLIST.md §6c describes it -- a documented trap that still catches its own author is a
    # trap to remove, not to document harder.
    if not (build_dir / "CMakeCache.txt").is_file():
        args += [
            "-DBUILD_SHARED_LIBS=ON",
            "-DCPP_PINYIN2_BUILD_TESTS=OFF",
            "-DCPP_PINYIN2_BUILD_EXAMPLES=OFF",
            "-DCPP_PINYIN2_INSTALL=OFF",
        ]
    args += [
        # The build TYPE, not just the `--config` passed to `cmake --build`: with a single-config
        # generator (Ninja, Makefiles) that flag is a no-op, so without this line the tree carries no
        # CMAKE_BUILD_TYPE at all -- no optimisation, and the part that bites, no -DNDEBUG. assert()
        # then stays LIVE inside the library that ships in the wheel, and
        # `assert(a.rowMode != 1 || decided >= 1)` in `src/EngineImpl.cpp` documents itself as compiled out under
        # the release 口径 ("where the equivalence gate is what protects it"). Measured 2026-10-06: with that flag
        # missing, the conformance case m-tone3-people ("中国人民") aborted the whole pytest process
        # (SIGABRT, "Assertion failed: decided >= 1, ... EngineImpl.cpp, line 512") before any test
        # could report -- reachable through the C ABI alone, so it was the package, not the shell,
        # that disagreed with the fixture. Multi-config generators ignore this variable and use
        # `--config` below, which is why both are passed.
        f"-DCMAKE_BUILD_TYPE={config}",
    ]
    if sys.platform == "win32":
        # Static MinGW runtime. ctypes does not search PATH for a DLL's dependencies, so a
        # dynamically linked libstdc++-6 / libgcc_s_seh-1 / libwinpthread-1 turns into
        # "FileNotFoundError: the file is missing" for a file that is right there
        # (section 6.5, item 6).
        args.append(
            "-DCMAKE_SHARED_LINKER_FLAGS=-static -static-libgcc -static-libstdc++"
        )
    elif sys.platform.startswith("linux"):
        # Section 6.5 item 4, measured on the board before and after rather than assumed. Before: ldd
        # showed libstdc++.so.6, libgcc_s.so.1, libc.so.6 and libm.so.6, and objdump -T found 94
        # GLIBCXX_/CXXABI_ symbol references. After: ldd shows libc.so.6 alone, zero GLIBCXX_/CXXABI_
        # references, and the highest glibc symbol version the library needs is GLIBC_2.17 -- against a
        # board running glibc 2.31. The library gets bigger (1067512 to 3038392 bytes) because the two
        # compiler runtimes are now inside it, which is the trade a manylinux-shaped wheel makes.
        # macOS is deliberately not in this branch: it has no libstdc++ (it uses libc++, whose static
        # form is not something to link into a wheel), so there is nothing to make static there.
        args.append("-DCMAKE_SHARED_LINKER_FLAGS=-static-libgcc -static-libstdc++")
    run(args)
    run(["cmake", "--build", str(build_dir), "--config", config])


def find_library(build_dir: Path, config: str) -> Path:
    candidates = sorted(
        (
            path
            for path in build_dir.rglob("*")
            if path.is_file()
            and path.suffix.lower() in SUFFIXES
            and "cpp-pinyin2" in path.name
        ),
        # THE REQUESTED CONFIGURATION WINS. A multi-config generator keeps Debug/ and Release/ side by side and
        # names the library identically in both, so ranking on `bin` alone left the choice to the filesystem's
        # own order -- the same shape as the install-consumer defect (a Debug consumer against a Release DLL is
        # the CRT split that hung the Windows runner, see the 2026-10-23 install-smoke commits). On a
        # single-config generator every candidate has the same parent, so this term is a no-op there. `bin`
        # stays second because that is where the DLL lands on Windows; the name keeps the pick deterministic.
        key=lambda path: (
            path.parent.name.lower() != config.lower(),
            path.parent.name != "bin",
            path.name,
        ),
    )
    if not candidates:
        raise SystemExit(f"FATAL: no cpp-pinyin2 library built under {build_dir}")
    if len(candidates) > 1:
        print("note: several candidates, using the first:")
        for path in candidates:
            print(f"  {path.relative_to(build_dir)}")
    return candidates[0]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def stage_library(library: Path) -> None:
    """Copy the library into the package and record its real name (decision D20=A)."""
    if NATIVE_DIR.exists():
        shutil.rmtree(NATIVE_DIR)
    NATIVE_DIR.mkdir(parents=True)
    target = NATIVE_DIR / library.name
    shutil.copy2(library, target)
    with (NATIVE_DIR / "name.txt").open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(library.name + "\n")
    print(f"staged {target.relative_to(ROOT)} (sha256 {sha256(target)[:16]}...)")


def stage_dict() -> None:
    """Copy the dictionaries the project ships, and refuse anything else."""
    if DICT_DIR.exists():
        shutil.rmtree(DICT_DIR)
    for dialect in DIALECTS:
        source = ROOT / "data" / "dialects" / dialect
        if not source.is_dir():
            raise SystemExit(f"FATAL: {source} is missing")
        target = DICT_DIR / dialect
        target.mkdir(parents=True)
        for entry in sorted(source.iterdir()):
            if entry.is_file():
                shutil.copy2(entry, target / entry.name)

    present = sorted(p.name for p in DICT_DIR.iterdir() if p.is_dir())
    if present != sorted(DIALECTS):
        raise SystemExit(f"FATAL: staged dialect dirs {present} != {sorted(DIALECTS)}")
    for dialect in DIALECTS:
        files = sorted(p.name for p in (DICT_DIR / dialect).iterdir() if p.is_file())
        missing = [table for table in REQUIRED_TABLES if table not in files]
        if missing:
            raise SystemExit(f"FATAL: {dialect} is missing {missing}")
        print(f"staged data/dict/{dialect}: {len(files)} files {files}")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--build-dir",
        default=str(ROOT / ".tmp" / "build-python"),
        help="CMake build directory (default: .tmp/build-python)",
    )
    parser.add_argument("--config", default="Release", help="build configuration")
    options = parser.parse_args(argv)

    build_dir = Path(options.build_dir).resolve()
    version = single_source_version()
    commit = commit_id()

    write_version(version, commit)
    configure_and_build(build_dir, options.config)
    stage_library(find_library(build_dir, options.config))
    stage_dict()

    print(f"\nready: version={version} commit={commit} build_dir={build_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
