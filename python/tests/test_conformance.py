"""The Python shell against the cross-language fixture (conformance/cases.json).

This is the Python half of plan section 6.7.6: both shells read the same file and assert the same
things, so a shell cannot quietly disagree with the engine or with the other shell. The C# half
lands with P3a-2c.

WHAT THIS FILE CAN AND CANNOT CATCH. The fixture's expected values were generated by the engine
itself (decision D35), so it is a lock against *drift*, not an oracle for *wrongness*: if the engine
changes and the fixture is regenerated, these tests stay green and say nothing about correctness.
The independent oracle stays in the C++ suite. What the lock buys is that the shell is held to the
engine's exact behaviour -- span boundaries, failure marking, candidate ordering, tone styles, the
ü/v switch -- by a file that a second language will be held to as well.

The four reconciliation checks (section 6.8.4) live at the bottom, together with the two guards that
matter most: the fixture must not be empty (an empty fixture makes every parametrised test below
disappear while pytest still reports success) and every case must be one this consumer actually
runs (a new op or dialect in the fixture must fail here, not be skipped silently).
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
from typing import Any, Dict, Iterator, List

import pytest

import cpp_pinyin2
from cpp_pinyin2 import OnError, Style, _ffi

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
FIXTURE_PATH = REPO_ROOT / "conformance" / "cases.json"
SHA_PATH = REPO_ROOT / "conformance" / "cases.sha256"
DOC_PATH = REPO_ROOT / "docs" / "PLUGIN_INTERFACE_AND_BINDINGS.md"

DIALECT_WHITELIST = frozenset({"mandarin", "cantonese"})
KNOWN_OPS = frozenset({"query", "readings", "to_simplified", "is_polyphonic",
                        "style_list", "render_syllable", "apply_tone_sandhi"})

#: Ops the PYTHON shell does not expose as its own public method. They are in the fixture on purpose and
#: are run here against the C ABI through ``_ffi`` (which this shell sits on), so "C-ABI-only" means
#: "compared against the C surface, not against a Python-level API" -- NOT "skipped". 2026-10-20, audit
#: round 2 B18: before this, none of the three appeared in any cross-language fixture at all.
C_ABI_ONLY_OPS = frozenset({"style_list", "render_syllable", "apply_tone_sandhi"})

#: The row in section 0a that is the *only* place the fixture's size is registered. The status cell
#: is cell 1 of the table row (cell 0 is the label); reading the wrong cell would happily match the
#: "49" that also appears in the row's evidence text.
REGISTRY_LABEL = "P3 夹具条数"
REGISTRY_STATUS_CELL = 1


def _load_fixture() -> Dict[str, Any]:
    """Load the fixture. Missing or empty is a hard failure, never a skip."""
    if not FIXTURE_PATH.is_file():
        raise RuntimeError(
            f"{FIXTURE_PATH} is missing. It is tracked: generate it with "
            f"'CApiSmoke <build>/bin/dict --emit-conformance conformance/cases.json <commit>'."
        )
    document = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))
    if not document.get("cases"):
        raise RuntimeError(f"{FIXTURE_PATH} carries no cases; every test below would vanish silently")
    return document


FIXTURE = _load_fixture()
CASES: List[Dict[str, Any]] = FIXTURE["cases"]


@pytest.fixture(scope="module")
def engines(repo_root: pathlib.Path) -> Iterator[Dict[str, cpp_pinyin2.Engine]]:
    """One engine per dialect, over ``data/dialects`` -- the single source of truth for the dictionaries.

    The generator read ``<build>/bin/dict``, which the build copies from the same ``data/dialects``; using
    it here rather than the nested copy inside the Python package keeps this test independent of
    whether the packaging step has run.
    """
    built = {
        dialect: cpp_pinyin2.Engine(dialect, repo_root / "data" / "dialects")
        for dialect in sorted(DIALECT_WHITELIST)
    }
    try:
        yield built
    finally:
        for engine in built.values():
            engine.close()


def _spans(engine: cpp_pinyin2.Engine, case: Dict[str, Any]) -> List[Dict[str, Any]]:
    result = engine.query(
        case["text"],
        style=Style(case["style"]),
        include_candidates=case["candidates"],
        v_to_u=case["vToU"],
        on_error=OnError.DEFAULT,
    )
    return [
        {
            "text": span.text,
            # The fixture's schema-1 key is "reading"/"failed"; the shell's own fields are
            # `rendered`/`failure_kind` (the C ABI renamed them: the string is the span's ONE
            # rendering and it equals `text` on a failure, and the failure is a classification).
            "reading": span.rendered,
            "failed": span.failure_kind != _ffi.OK,
            "candidates": list(span.candidates),
        }
        for span in result
    ]


QUERY_CASES = [case for case in CASES if case["op"] == "query"]
READINGS_CASES = [case for case in CASES if case["op"] == "readings"]
SIMPLIFY_CASES = [case for case in CASES if case["op"] == "to_simplified"]
POLYPHONIC_CASES = [case for case in CASES if case["op"] == "is_polyphonic"]
STYLE_LIST_CASES = [case for case in CASES if case["op"] == "style_list"]
RENDER_CASES = [case for case in CASES if case["op"] == "render_syllable"]
SANDHI_CASES = [case for case in CASES if case["op"] == "apply_tone_sandhi"]


def test_c_abi_only_ops_are_present_and_carry_measured_values() -> None:
    """The three ops that have no Python-level entry point are still COVERED -- by measurement, not by a skip.

    ``style_list`` / ``render_syllable`` / ``apply_tone_sandhi`` are C-surface operations: the Python shell
    exposes no public method for any of them, so there is no second Python-level answer to compare against.
    What makes them covered is that the fixture's values were PRODUCED by running the C ABI
    (``CApiSmoke --emit-conformance``), so a behavioural regression on any of the three changes the fixture
    on the next regeneration instead of passing unnoticed. Before 2026-10-20 none of the three appeared in
    any cross-language fixture at all (audit round 2, B18).

    This test is the anti-shrink guard for them: the cases must exist, and their expectations must be
    non-empty, so deleting a case or emptying its expectation cannot look like success.
    """
    present = {case["op"] for case in CASES}
    missing = C_ABI_ONLY_OPS - present
    assert not missing, f"C-ABI-only ops disappeared from the fixture: {sorted(missing)}"
    for case in CASES:
        if case["op"] == "style_list":
            assert case["expect_styles"], case["id"]
        elif case["op"] == "render_syllable":
            assert case["expect"], case["id"]
        elif case["op"] == "apply_tone_sandhi":
            assert case["expect_rendered"], case["id"]
            assert case["expect_changed"] >= 0, case["id"]
    # At least one sandhi case must actually CHANGE something, or the op would be covered by a pass that
    # does nothing -- the exact shape a zero-filled opts struct produced while this was being written.
    assert any(c["expect_changed"] > 0 for c in CASES if c["op"] == "apply_tone_sandhi"), \
        "every apply_tone_sandhi case reports 0 changes: the pass is not doing anything"


@pytest.mark.parametrize("case", QUERY_CASES, ids=[case["id"] for case in QUERY_CASES])
def test_query_case_matches_the_fixture(case: Dict[str, Any], engines) -> None:
    assert _spans(engines[case["dialect"]], case) == case["expect_syllables"]


@pytest.mark.parametrize("case", READINGS_CASES, ids=[case["id"] for case in READINGS_CASES])
def test_readings_case_matches_the_fixture(case: Dict[str, Any], engines) -> None:
    # BOTH switches are passed through rather than ignored (they are fixture fields for this op: the C
    # ABI honours them for readings). `case.get` because the frozen fixture carries `vToU` only today --
    # a switch the case does not name means "leave it at the library default", not "force it false".
    got = engines[case["dialect"]].readings(
        case["text"],
        style=Style(case["style"]),
        v_to_u=case.get("vToU", False),
        mark_neutral_as_5=case.get("markNeutralAs5", False),
    )
    assert list(got) == case["expect_readings"]


def test_readings_honours_the_two_switches(engines) -> None:
    """``readings`` passes ``v_to_u`` / ``mark_neutral_as_5`` through instead of dropping them.

    The gap this closes was recorded as an assertion ("no readings case sets ``vToU``") rather than
    as a test of the feature, so the feature had no positive evidence at all. Every expectation here
    is MEASURED (this shell against ``data/dialects``), never chosen: the C ABI has always honoured
    both switches for readings, so this is what a C caller and a Python caller now agree on.
    """
    mandarin = engines["mandarin"]
    nv = "\u5973"      # 女
    de = "\u7684"      # 的
    xing = "\u884c"    # 行

    # v_to_u decides which STRING a reading is: ü is written v by default, so the switch is what
    # makes the second reading of 女 a different string rather than a toneless variant of the first.
    assert mandarin.readings(nv, style=Style.NORMAL) == ["nv"]
    assert mandarin.readings(nv, style=Style.NORMAL, v_to_u=True) == ["nv", "n\u00fc"]
    assert mandarin.readings(nv, style=Style.TONE3) == ["nv3", "nv"]
    assert mandarin.readings(nv, style=Style.TONE3, v_to_u=True) == ["nv3", "n\u00fc"]

    # mark_neutral_as_5 decides whether a neutral row reports its tone: 的's first row spells no
    # tone, and 行's third row is the toneless variant, so the two sides differ in the COUNT of
    # readings that carry a tone instead of in a suffix.
    assert mandarin.readings(de, style=Style.TONE3) == ["de", "di4", "di1", "di2"]
    assert mandarin.readings(de, style=Style.TONE3, mark_neutral_as_5=True) == [
        "de5",
        "di4",
        "di1",
        "di2",
    ]
    assert mandarin.readings(xing, style=Style.TONE3, mark_neutral_as_5=True) == [
        "xing2",
        "hang2",
        "xing5",
        "heng2",
    ]

    # Both switches are masked by the dialect's capability flags, exactly as on `query`: Cantonese
    # declares neither capability, so asking for them is ignored rather than reinterpreted.
    cantonese = engines["cantonese"]
    plain = cantonese.readings(nv, style=Style.TONE3)
    assert cantonese.readings(nv, style=Style.TONE3, v_to_u=True, mark_neutral_as_5=True) == plain


