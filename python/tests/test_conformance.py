def _rebuild_scale_text(scale: Dict[str, Any]) -> str:
    """Rebuild the scale input from the block alone.

    Deliberately a second implementation of the generator's loop: the block carries the seed, the LCG
    constants, the modulus, the 32-bit mask and the alphabet precisely so that a consumer in any
    language can reproduce the text without sharing code with the generator.
    """
    x = scale["seed"]
    characters: List[str] = []
    for _ in range(scale["length"]):
        x = (x * scale["multiplier"] + scale["increment"]) & scale["mask"]
        x %= scale["modulus"]
        characters.append(scale["alphabet"][x % len(scale["alphabet"])])
    return "".join(characters)


def test_scale_block_rebuilds_to_the_same_input(engines) -> None:
    scale = FIXTURE["scale"]
    text = _rebuild_scale_text(scale)
    assert len(text) == scale["length"], "rebuilt input is not the declared length"

    spans = engines[scale["dialect"]].query(text, style=Style(scale["style"]), include_candidates=False)
    assert len(spans) == scale["expect_span_count"], (
        f"the 4096-character input produced {len(spans)} spans, the fixture records "
        f"{scale['expect_span_count']}"
    )
    head, tail = scale["expect_head"], scale["expect_tail"]
    assert [span.rendered for span in spans[: len(head)]] == head
    assert [span.rendered for span in spans[-len(tail) :]] == tail


# --- the two guards that keep this file honest ------------------------------------------------


def test_the_fixture_is_not_empty() -> None:
    """An empty (or all-unknown-op) fixture would leave pytest reporting success with nothing run."""
    assert len(CASES) >= 40, f"the fixture shrank to {len(CASES)} cases"


def test_every_case_is_one_this_consumer_runs() -> None:
    ops = {case["op"] for case in CASES}
    dialects = {case["dialect"] for case in CASES}
    assert ops <= KNOWN_OPS, f"the fixture uses ops this consumer would skip: {sorted(ops - KNOWN_OPS)}"
    assert dialects <= DIALECT_WHITELIST, f"the fixture uses dialects outside the whitelist: {sorted(dialects - DIALECT_WHITELIST)}"
    covered = len(QUERY_CASES) + len(READINGS_CASES) + len(SIMPLIFY_CASES) + len(POLYPHONIC_CASES)
    # The three C-ABI-only ops have no Python-level handler of their own; they are guarded by
    # `test_c_abi_only_ops_are_present_and_carry_measured_values` instead of being dropped from the count.
    # Counting them here is what keeps "every case is one this consumer runs" true rather than "every case
    # except the ones we chose not to run".
    covered += len(STYLE_LIST_CASES) + len(RENDER_CASES) + len(SANDHI_CASES)
    assert covered == len(CASES), f"{len(CASES) - covered} case(s) match no op handler"


def test_readings_cases_use_switches_the_shell_can_express() -> None:
    """``Engine.readings`` must be able to pass through every switch a readings case sets.

    This used to be a guard for a gap instead of a check: the shell took only a style, while the C
    ABI honours ``v_to_u`` / ``mark_neutral_as_5`` for readings too -- so the assertion was "no
    readings case sets ``vToU``", which would fail the moment the generator emitted one. The gap is
    closed (both switches are parameters, and ``test_readings_honours_the_two_switches`` proves they
    are forwarded rather than dropped), so this guard's job is the other half: every key a readings
    case carries is classified here, so a NEW switch in the fixture is a red test instead of a field
    this consumer quietly never reads.
    """
    switch_keys = {"vToU", "markNeutralAs5"}          # passed to the library by `readings`
    expectation_keys = {"expect_readings", "expect_syllables"}
    # What this consumer sends. `candidates` is in the frozen case shape but is consumed by the QUERY
    # handler only (`_spans`); it is listed so the key census stays complete, not because `readings`
    # reads it.
    input_keys = {"id", "dialect", "op", "text", "style", "candidates"}
    known = switch_keys | expectation_keys | input_keys
    unknown = sorted({key for case in READINGS_CASES for key in case} - known)
    assert not unknown, (
        f"the readings cases carry keys this test has not classified: {unknown}. Classify each one as "
        f"a switch `Engine.readings` passes through, an expectation it compares, or an input it sends."
    )


# --- the four reconciliation checks of section 6.8.4 -------------------------------------------


def test_reconcile_1_cases_count_matches_the_case_list() -> None:
    assert FIXTURE["cases_count"] == len(CASES)


def test_reconcile_2_file_bytes_match_the_pinned_sha256() -> None:
    pinned = SHA_PATH.read_text(encoding="ascii").split()[0].strip().lower()
    digest = hashlib.sha256(FIXTURE_PATH.read_bytes()).hexdigest()
    assert digest == pinned, (
        f"conformance/cases.json hashes to {digest}, the pinned value is {pinned}: the fixture was "
        f"edited without regenerating it (or regenerated without re-pinning)"
    )


def _registry_count() -> int:
    """The count registered in section 0a -- the single place that number is allowed to live."""
    for line in DOC_PATH.read_text(encoding="utf-8").splitlines():
        if REGISTRY_LABEL in line:
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            match = re.search(r"\*\*(\d+)\s*（", cells[REGISTRY_STATUS_CELL])
            assert match, (
                f"the '{REGISTRY_LABEL}' row's status cell carries no number: "
                f"{cells[REGISTRY_STATUS_CELL]!r}"
            )
            return int(match.group(1))
    pytest.fail(
        f"no '{REGISTRY_LABEL}' row in {DOC_PATH.name}: the fixture's size has no registry to be "
        f"checked against, and a fixture can then be shrunk without anyone noticing"
    )


def test_reconcile_3_count_matches_the_registry_in_the_document() -> None:
    assert FIXTURE["cases_count"] == _registry_count()


def test_reconcile_4_dialects_match_the_registry_the_runtime_and_res_dict(repo_root: pathlib.Path) -> None:
    fixture_dialects = set(FIXTURE["dialects"])
    runtime = set(cpp_pinyin2.dialect_ids())
    on_disk = {entry.name for entry in (repo_root / "data" / "dialects").iterdir() if entry.is_dir()}
    assert fixture_dialects == runtime, f"fixture {sorted(fixture_dialects)} vs runtime {sorted(runtime)}"
    assert runtime == on_disk, f"runtime {sorted(runtime)} vs data/dialects {sorted(on_disk)}"
    assert runtime == DIALECT_WHITELIST, (
        f"the runtime registers {sorted(runtime)}, the whitelist is {sorted(DIALECT_WHITELIST)}"
    )
